def normalize_key(name: str) -> str:
    """Helper to normalize disease names for resilient dictionary lookup."""
    return name.strip().lower().replace("___", "_").replace("__", "_").replace(" ", "_")

# Precompute normalized index for fast, case-insensitive, punctuation-tolerant lookup
_NORMALIZED_MAP = {
    normalize_key(key): val
    for key, val in RECOMMENDATIONS.items()
}

def get_recommendation(disease: str):
    """
    Retrieves agronomic causes and actionable treatments for any plant disease class.
    Supports exact keys, normalized keys, and smart fallbacks.
    """
    if not disease:
        return RECOMMENDATIONS["No disease detected"]

    # 1. Direct match
    if disease in RECOMMENDATIONS:
        return RECOMMENDATIONS[disease]

    # 2. Normalized match (handles casing, spaces, underscore differences)
    norm = normalize_key(disease)
    if norm in _NORMALIZED_MAP:
        return _NORMALIZED_MAP[norm]

    # 3. Partial / Substring match in normalized keys
    for k_norm, rec in _NORMALIZED_MAP.items():
        if norm in k_norm or k_norm in norm:
            return rec

    # 4. Smart fallback if class indicates healthy
    if "healthy" in norm:
        return {
            "cause": "Healthy foliage detected with no visible pathology.",
            "treatment": "Continue standard crop management, balanced fertilization, and regular leaf monitoring."
        }

    # 5. General fallback
    readable_name = disease.replace("___", " ").replace("__", " ").replace("_", " ")
    return {
        "cause": f"Pathological symptoms detected on {readable_name}.",
        "treatment": "Isolate affected foliage, apply broad-spectrum bio-fungicide/neem oil, and consult an agronomist."
    }
